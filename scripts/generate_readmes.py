#!/usr/bin/env python3
"""Generate directory inventories without interpreting file contents.

Run: python3 scripts/generate_readmes.py
Check: python3 scripts/generate_readmes.py --check
Optional local hook: git config core.hooksPath .githooks

Inputs are existing Git-tracked and non-ignored untracked files. Standard
README.md files are outputs, never content inputs. Gitignored untracked files
are excluded. Named source documents such as home_assistant_system_README.md
remain ordinary inputs. No document titles, purpose, status or authority are
inferred. SHA-256 records bytes, not freshness or truth of the contents.
"""
from __future__ import annotations

import argparse
import hashlib
import html
import os
from pathlib import Path
import subprocess
from urllib.parse import quote


def label(value: str) -> str:
    return html.escape(value).replace('|', '&#124;').replace('\n', '&#10;').replace('\r', '&#13;').replace('`', '&#96;').replace('[', '&#91;').replace(']', '&#93;')


def inventory(root: Path) -> dict[Path, str]:
    raw = subprocess.check_output(
        ['git', 'ls-files', '-z', '--cached', '--others', '--exclude-standard'], cwd=root
    )
    paths = sorted({Path(os.fsdecode(p)) for p in raw.split(b'\0') if p})
    directories = {Path('.')}
    files: dict[Path, list[tuple[str, str, str, str]]] = {}
    for relative in paths:
        path = root / relative
        # Never traverse symlinked directories or submodule working trees.
        if any((root / parent).is_symlink() for parent in relative.parents):
            continue
        if not path.is_symlink() and not path.is_file():
            continue
        directories.update(relative.parents)
        if relative.name == 'README.md':
            if path.is_symlink():
                raise ValueError(f'Refusing to replace symlink: {relative}')
            continue
        if path.is_symlink():
            data = os.fsencode(os.readlink(path))
            kind = 'symlink (link text)'
        else:
            data = path.read_bytes()
            kind = 'file'
        files.setdefault(relative.parent, []).append(
            (relative.name, kind, str(len(data)), hashlib.sha256(data).hexdigest())
        )
    result = {}
    for directory in sorted(directories):
        rows = []
        for child in sorted(d for d in directories if d != directory and d.parent == directory):
            rows.append(f'| [<code>{label(child.name)}/</code>](./{quote(child.name, safe="")}/README.md) | directory | — | — |')
        for name, kind, size, digest in files.get(directory, []):
            rows.append(f'| [<code>{label(name)}</code>](./{quote(name, safe="")}) | {kind} | {size} | `{digest}` |')
        text = (
            '<!-- Generated by scripts/generate_readmes.py; do not edit. -->\n'
            f'# Inventory: <code>{label(directory.as_posix())}</code>\n\n'
            'Existing tracked and non-ignored files only. Generated README.md files are excluded from file entries.\n'
            'Hashes describe file bytes (or symlink text), not semantic status or authority.\n\n'
        )
        text += ('| Entry | Kind | Bytes | SHA-256 |\n| --- | --- | ---: | --- |\n' + '\n'.join(rows) + '\n') if rows else 'No inventory entries.\n'
        result[directory / 'README.md'] = text
    return result


def generate(root: Path, check: bool = False) -> list[Path]:
    expected = inventory(root)
    changed = []
    for relative, content in expected.items():
        path = root / relative
        if path.is_symlink():
            raise ValueError(f'Refusing to replace symlink: {relative}')
        if not path.exists() or path.read_bytes() != content.encode('utf-8'):
            changed.append(relative)
            if not check:
                path.write_bytes(content.encode('utf-8'))
    return changed


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='Fail when inventories need regeneration; write nothing.')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    changed = generate(root, check=args.check)
    for path in changed:
        print(f'{"STALE" if args.check else "UPDATED"} {path}')
    if args.check and changed:
        print('Run python3 scripts/generate_readmes.py and commit the generated READMEs.')
        return 1
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
